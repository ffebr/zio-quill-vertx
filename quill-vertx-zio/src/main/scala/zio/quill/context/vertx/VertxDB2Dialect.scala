package zio.quill.context.vertx

import zio.quill.{IdiomContext, NamingStrategy}
import zio.quill.ast._
import zio.quill.context.{CanInsertReturningWithSingleValue, CanInsertWithMultiValues, CanReturnClause}
import zio.quill.context.sql._
import zio.quill.context.sql.idiom._
import zio.quill.context.sql.idiom.SqlIdiom.ActionTableAliasBehavior
import zio.quill.idiom.{Statement, StringToken, Token}
import zio.quill.idiom.StatementInterpolator._
import zio.quill.norm.ExpandReturning
import zio.quill.quat.Quat
import zio.quill.sql.idiom.BooleanLiteralSupport
import zio.quill.util.Messages.fail

/** DB2 LUW SQL generation for Vert.x prepared queries (`?` parameters). */
trait VertxDB2Dialect
    extends SqlIdiom
    with QuestionMarkBindVariables
    with NoConcatSupport
    with BooleanLiteralSupport
    with CanReturnClause
    with CanInsertWithMultiValues
    with CanInsertReturningWithSingleValue {

  override def useActionTableAliasAs: ActionTableAliasBehavior = ActionTableAliasBehavior.SkipAs

  // DB2 regular identifiers cannot begin with an underscore. Quill uses `_1`, `_2`, ...
  // as aliases for tuple projections, so emit those as delimited identifiers.
  override protected def tokenizeColumnAlias(strategy: NamingStrategy, column: String): String =
    if (column.startsWith("_")) "\"" + column.replace("\"", "\"\"") + "\"" else column

  override def prepareForProbing(string: String): String = string

  override def defaultAutoGeneratedToken(field: Token) = stmt"($field) VALUES (DEFAULT)"

  private val emptySetContains: Token = StringToken("1 <> 1")

  override def emptySetContainsToken(field: Token): Token = emptySetContains

  override protected def limitOffsetToken(
    query: Statement
  )(implicit astTokenizer: Tokenizer[Ast], strategy: NamingStrategy): Tokenizer[(Option[Ast], Option[Ast])] =
    Tokenizer[(Option[Ast], Option[Ast])] {
      case (Some(limit), None)         => stmt"$query FETCH FIRST ${limit.token} ROWS ONLY"
      case (Some(limit), Some(offset)) => stmt"$query OFFSET ${offset.token} ROWS FETCH NEXT ${limit.token} ROWS ONLY"
      case (None, Some(offset))        => stmt"$query OFFSET ${offset.token} ROWS"
      case (None, None)                => query
    }

  private class DB2FlattenSqlQueryTokenizerHelper(q: FlattenSqlQuery)(implicit
    astTokenizer: Tokenizer[Ast],
    strategy: NamingStrategy,
    idiomContext: IdiomContext
  ) extends FlattenSqlQueryTokenizerHelper(q)(astTokenizer, strategy, idiomContext) {
    override def withFrom: Statement =
      if (q.from.isEmpty) stmt"$withDistinct FROM SYSIBM.SYSDUMMY1"
      else super.withFrom
  }

  override implicit def sqlQueryTokenizer(implicit
    astTokenizer: Tokenizer[Ast],
    strategy: NamingStrategy,
    idiomContext: IdiomContext
  ): Tokenizer[SqlQuery] = Tokenizer[SqlQuery] {
    case query: FlattenSqlQuery => new DB2FlattenSqlQueryTokenizerHelper(query).apply
    case other                  => super.sqlQueryTokenizer.token(other)
  }

  // BooleanLiteralSupport can treat toInt/toLong as boolean expressions in scalar
  // projections. Lower those casts before it can wrap them in `CASE WHEN ...`, which
  // DB2 then interprets as a boolean test on a number.
  override def normalizeAst(
    ast: Ast,
    concatBehavior: zio.quill.norm.ConcatBehavior,
    equalityBehavior: zio.quill.norm.EqualityBehavior,
    idiomContext: IdiomContext
  ): Ast = {
    val lowered                      = VertxDB2Dialect.LowerStringNumericCasts(ast)
    def scalarQuery(value: Ast): Ast = {
      val dummy = Entity.Opinionated(
        "SYSIBM.SYSDUMMY1",
        Nil,
        Quat.Product.empty("DB2ScalarSource"),
        Renameable.Fixed
      )
      Map(dummy, Ident("db2_scalar_source", dummy.quat), value)
    }
    val scalarCast = ast match {
      case UnaryOperation(StringOperator.`toInt`, _) | UnaryOperation(StringOperator.`toLong`, _) =>
        Some(lowered)
      // QueryMacro wraps root scalar expressions in Map(op, x, x) before invoking
      // the dialect. Replace that shape with a real DB2 single-row SELECT source.
      case Map(operation @ UnaryOperation(operator, _), alias, Ident(name, _))
          if alias.name == name && (operator == StringOperator.`toInt` || operator == StringOperator.`toLong`) =>
        Some(VertxDB2Dialect.LowerStringNumericCasts(operation: Ast))
      case _ => None
    }
    val normalizedInput = scalarCast match {
      case Some(value) => scalarQuery(value)
      case None        => lowered
    }
    super.normalizeAst(normalizedInput, concatBehavior, equalityBehavior, idiomContext)
  }

  override protected def actionTokenizer(insertEntityTokenizer: Tokenizer[Entity])(implicit
    astTokenizer: Tokenizer[Ast],
    strategy: NamingStrategy,
    idiomContext: IdiomContext
  ): Tokenizer[Action] = Tokenizer[Action] {
    case returning: ReturningAction if returningEnabled =>
      val tableFunction = returning.action match {
        case _: Delete => "OLD TABLE"
        case _: Insert => "FINAL TABLE"
        case _: Update => "FINAL TABLE"
        case other     => fail(s"DB2 table-returning is unsupported for action: $other")
      }
      val projected = returnListTokenizer.token(
        ExpandReturning(returning, Some(returning.alias.name))(this, strategy, idiomContext).map(_._1)
      )
      returning.action match {
        case Insert(table: Entity, Nil) =>
          stmt"SELECT $projected FROM FINAL TABLE (INSERT INTO ${table.token} ${defaultAutoGeneratedToken(
              returning.property.token
            )}) AS ${returning.alias.name.token}"
        case action =>
          stmt"SELECT $projected FROM ${tableFunction.token} (${action.token}) AS ${returning.alias.name.token}"
      }
    case other => super.actionTokenizer(insertEntityTokenizer).token(other)
  }
}

object VertxDB2Dialect extends VertxDB2Dialect {
  // An untyped parameter in CAST(? AS INTEGER) is described by Db2 as INTEGER,
  // which rejects a native String binding. Declare the string input explicitly.
  private object LowerStringNumericCasts extends StatelessTransformer {
    override def apply(ast: Ast): Ast =
      ast match {
        case UnaryOperation(StringOperator.`toInt`, value) =>
          Infix(List("CAST(CAST(", " AS VARCHAR(32672)) AS INTEGER)"), List(apply(value)), pure = true, transparent = false, quat = Quat.Value)
        case UnaryOperation(StringOperator.`toLong`, value) =>
          Infix(List("CAST(CAST(", " AS VARCHAR(32672)) AS BIGINT)"), List(apply(value)), pure = true, transparent = false, quat = Quat.Value)
        case other => super.apply(other)
      }
  }
}
